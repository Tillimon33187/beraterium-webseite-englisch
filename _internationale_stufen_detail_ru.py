def apply_stage_locale(stage: dict, locale: str) -> dict:
    """Return copy of stage with locale-specific text fields."""
    if locale != "ru":
        return stage
    ov = STAGE_RU_OVERRIDES.get(stage.get("nr", ""), {})
    if not ov:
        return stage
    out = dict(stage)
    out.update(ov)
    return out
